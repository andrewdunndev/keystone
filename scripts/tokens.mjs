// Writes src/tokens.js: the design tokens the approval pages use, read from @dunn.dev/reference, so the Worker carries
// them inline and fetches nothing. Run `npm run tokens` after bumping the package; test/tokens.test.js fails on a stale file.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const dir = fileURLToPath(new URL('../node_modules/@dunn.dev/reference/tokens/', import.meta.url));
const OUT = fileURLToPath(new URL('../src/tokens.js', import.meta.url));

// Every token the page CSS reads. A token outside this list is not emitted.
export const WANTED = [
  'bg', 'surface', 'border', 'border-strong', 'text', 'text-2', 'text-muted', 'accent', 'accent-hover', 'accent-contrast',
  'danger', 'danger-subtle', 'success', 'success-subtle', 'warning', 'warning-subtle',
  'font-body', 'font-mono', 'text-xs', 'text-sm', 'text-base', 'text-3xl', 'lh-base', 'lh-hero',
  'space-2', 'space-3', 'space-4', 'space-5', 'space-6', 'space-8', 'radius',
];

const read = (f) => readFileSync(dir + f, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
// The body of the first block whose selector text matches, braces balanced.
function block(css, selector) {
  const at = css.indexOf(selector);
  if (at < 0) throw new Error(`tokens: no block ${selector}`);
  let i = css.indexOf('{', at), depth = 0;
  const start = i + 1;
  for (; i < css.length; i++) {
    if (css[i] === '{') depth++;
    else if (css[i] === '}' && --depth === 0) return css.slice(start, i);
  }
  throw new Error(`tokens: unbalanced ${selector}`);
}
function decls(body) {
  const m = new Map();
  for (const d of body.matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)) {
    const v = d[2].trim().replace(/\s+/g, ' ');
    if (/[^\w #%.,()'"+*/-]/.test(v)) throw new Error(`tokens: ${d[1]} carries a character outside plain CSS values`);
    m.set(d[1], v);
  }
  return m;
}

// Fully expands var() against the given maps, in order; a colour-mix keeps its var() so the subtle tints follow the
// element's own colour.
function expand(name, maps, need) {
  const get = (n) => maps.find((m) => m.has(n))?.get(n);
  const v = get(name);
  if (v === undefined) throw new Error(`tokens: ${name} is not defined`);
  if (v.startsWith('color-mix(')) {
    for (const r of v.matchAll(/var\((--[\w-]+)\)/g)) need.add(r[1]);
    return v;
  }
  return v.replace(/var\((--[\w-]+)\)/g, (_, n) => expand(n, maps, need));
}

export function render() {
  const colors = read('colors.css');
  const light = decls(block(colors, ':root,\n[data-theme="light"]'));
  const dark = decls(block(block(colors, '@media (prefers-color-scheme: dark)'), ':root:not([data-theme="light"])'));
  const shared = new Map([...decls(block(read('typography.css'), ':root')), ...decls(block(read('spacing.css'), ':root'))]);
  const names = new Set(WANTED.map((n) => `--${n}`));
  const l = [], d = [];
  for (const n of [...names]) {
    const need = new Set();
    if (shared.has(n)) { l.push(`${n}:${expand(n, [shared], need)}`); continue; }
    const lv = expand(n, [light], need), dv = expand(n, [dark, light], need);
    l.push(`${n}:${lv}`);
    if (dv !== lv) d.push(`${n}:${dv}`);
    for (const r of need) if (!names.has(r)) throw new Error(`tokens: ${n} needs ${r}; add it to WANTED`);
  }
  const css = `:root{${l.join(';')};color-scheme:light dark}@media(prefers-color-scheme:dark){:root{${d.join(';')}}}`;
  return `// Generated by scripts/tokens.mjs from @dunn.dev/reference. Do not edit.\nexport const TOKENS = ${JSON.stringify(css)};\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) writeFileSync(OUT, render());
