// Writes src/auth-css.js: the approval pages' stylesheet, read from @dunn.dev/reference, so the Worker carries it
// inline and fetches nothing. Run `npm run auth-css` after bumping the package; test/auth-css.test.js fails on a stale file.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const SRC = fileURLToPath(new URL('../node_modules/@dunn.dev/reference/auth/auth.standalone.css', import.meta.url));
const OUT = fileURLToPath(new URL('../src/auth-css.js', import.meta.url));

// The sheet is embedded in a <style> element, so a character that could end it or start an escape is refused, as is
// anything that could load a resource.
export function render(css = readFileSync(SRC, 'utf8')) {
  if (/[<\\]|[^\n\x20-\x7e]/.test(css)) throw new Error('auth-css: the stylesheet carries <, a backslash or a non-ASCII character');
  if (/url\(|@import/i.test(css)) throw new Error('auth-css: the stylesheet loads a resource');
  return `// Generated by scripts/auth-css.mjs from @dunn.dev/reference. Do not edit.\nexport const AUTH_CSS = ${JSON.stringify(css)};\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) writeFileSync(OUT, render());
